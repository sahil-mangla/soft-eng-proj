"""Measures run time, API latency, memory and CPU for the performance section of Chapter 10.

    python -m scripts.benchmark                  (from the repo root; takes about a minute)

Numbers depend on the machine, so the output records which one produced them.
"""

import json
import os
import platform
import resource
import statistics
import sys
import threading
import time
import tracemalloc
import urllib.request
from datetime import date
from http.server import ThreadingHTTPServer

from api.replay import build_replay
from api.server import Handler
from simulation.engine import RunMode
from simulation.scenario import Scenario, run_scenario

OUT = os.path.join("docs", "report", "generated", "benchmark.md")


def timed(fn, repeats=5):
    samples = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - t0)
    return statistics.median(samples), min(samples), max(samples)


def main() -> int:
    rows = []

    def add(name, stats, note=""):
        rows.append(f"| {name} | {stats[0] * 1000:.0f} | {stats[1] * 1000:.0f} | {stats[2] * 1000:.0f} | {note} |")

    # single simulation runs
    for label, sc in (("80 vehicles, 5x5 grid", Scenario()), ("200 vehicles, 5x5 grid", Scenario(background_vehicles=200)), ("400 vehicles, 5x5 grid (upper limit)", Scenario(background_vehicles=400)), ("80 vehicles, 8x8 grid (largest)", Scenario(grid_size=8))):
        add(f"One run, corridor + recovery, {label}", timed(lambda sc=sc: run_scenario(sc, RunMode.CORRIDOR_RECOVERY)))

    # the replay the UI loads (four runs with frames) and its size
    add("Build the four-mode replay (80 vehicles)", timed(lambda: build_replay(Scenario()), 3))
    size = len(json.dumps(build_replay(Scenario()), separators=(",", ":")))

    # HTTP latency
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{httpd.server_address[1]}"
    get = lambda p: urllib.request.urlopen(base + p).read()
    add("GET /api/replay (80 vehicles)", timed(lambda: get("/api/replay"), 5), f"{size / 1e6:.2f} MB of JSON")
    add("GET /api/replay (400 vehicles)", timed(lambda: get("/api/replay?vehicles=400"), 3))
    get("/api/compare?seeds=2&vehicles=10")  # start the shared process pool before timing
    add("GET /api/compare (12 seeds x 4 modes = 48 runs)", timed(lambda: get("/api/compare?seeds=12"), 3), "shared process pool")
    httpd.shutdown()

    # memory and CPU
    tracemalloc.start()
    run_scenario(Scenario(background_vehicles=400), RunMode.CORRIDOR_RECOVERY)
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    t0, c0 = time.perf_counter(), time.process_time()
    run_scenario(Scenario(), RunMode.CORRIDOR_RECOVERY)
    wall, cpu = time.perf_counter() - t0, time.process_time() - c0
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / (1 if sys.platform == "darwin" else 1024) / 1e6

    text = [
        f"<!-- generated by scripts/benchmark.py on {date.today()}; do not edit by hand -->",
        "",
        f"Machine: {platform.platform()}, {platform.processor() or platform.machine()}, {os.cpu_count()} logical CPUs, Python {platform.python_version()}.",
        "",
        "| Measurement | Median (ms) | Fastest (ms) | Slowest (ms) | Note |",
        "| --- | --- | --- | --- | --- |",
        *rows,
        "",
        f"- Peak Python allocation during one 400-vehicle run: {peak / 1e6:.1f} MB.",
        f"- Peak resident memory of the whole benchmark process (replay builds included): {rss:.0f} MB.",
        f"- CPU use of one default run: {cpu:.2f} s of CPU in {wall:.2f} s of wall time ({cpu / wall * 100:.0f}% of one core); the simulation is single-threaded.",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(text) + "\n")
    print("\n".join(text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
