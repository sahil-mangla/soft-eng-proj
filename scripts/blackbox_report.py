"""Executes every black-box case and writes the result tables used in Chapter 10.

    python -m scripts.blackbox_report            (from the repo root)
"""

import os
import sys
from datetime import date

from tests.blackbox_cases import CASES

OUT = os.path.join("docs", "report", "generated", "blackbox-results.md")


def main() -> int:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    results = [(c, *c.execute()) for c in CASES]
    lines = [f"<!-- generated by scripts/blackbox_report.py on {date.today()}; do not edit by hand -->", ""]
    for technique, title in (("EP", "Equivalence partitioning"), ("BVA", "Boundary value analysis"), ("State", "State transition"), ("Use case", "Use-case based")):
        rows = [r for r in results if r[0].technique == technique]
        lines += [f"### {title}", "", "| TC ID | Requirement | Case | Input | Expected | Actual | Status |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for case, actual, passed in rows:
            esc = lambda t: t.replace("|", "\\|")
            lines.append(f"| {case.id} | {case.requirement} | {esc(case.description)} | `{esc(case.input)}` | {esc(case.expected)} | {esc(actual)} | {'Pass' if passed else 'FAIL'} |")
        lines.append("")
    passed = sum(1 for r in results if r[2])
    lines.append(f"**{passed} of {len(results)} cases pass.**")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {passed}/{len(results)} pass")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
